const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const logosDir = path.join(root, "public", "logos");
const outFile = path.join(root, "src", "components", "ProviderIconMap.ts");

const mapping = {
  modelscope: "modelscope",
  dashscope: "bailian",
  siliconflow: "siliconcloud",
  xiaomi: "xiaomimimo",
  openai: "openai",
  anthropic: "anthropic",
  google: "google",
  groq: "groq",
  baidu: "baidu",
  tencent: "tencent",
  zhipu: "zhipu",
  qwen3_asr_realtime: "qwen",
  xinference: "xinference",
};

const monoBrandColors = {
  openai: "#10A37F",
  anthropic: "#D97757",
  groq: "#F55036",
  xiaomi: "#FF6900",
};

const lines = [];
const colorInfo = [];

Object.entries(mapping).forEach(([provider, base]) => {
  const colorFile = `${base}-color.svg`;
  const monoFile = `${base}.svg`;
  let file = monoFile;
  let mode = "mono";
  if (fs.existsSync(path.join(logosDir, colorFile))) {
    file = colorFile;
    mode = "color";
  }
  const filePath = path.join(logosDir, file);
  if (!fs.existsSync(filePath)) {
    console.warn(`Missing logo file: ${file}`);
    return;
  }
  const svg = fs.readFileSync(filePath, "utf-8").trim().replace(/\s+/g, " ");
  lines.push(`  "${provider}": ${JSON.stringify(svg)},`);
  const brandColor = monoBrandColors[provider];
  colorInfo.push(`  "${provider}": ${brandColor ? `"${brandColor}"` : "undefined"},`);
});

const content = `// Auto-generated by scripts/sync-provider-logos.cjs
export const providerSvgs: Record<string, string> = {
${lines.join("\n")}
};

export const providerIconColors: Record<string, string | undefined> = {
${colorInfo.join("\n")}
};
`;

fs.writeFileSync(outFile, content, "utf-8");
console.log(`Generated ${outFile} with ${lines.length} provider logos.`);
